-- кожному запуску курсу" на "розпакувати один раз під час завантаження, і
-- залити кожен файл окремо в Storage". Плеєр тепер просто відкриває реальний
-- публічний URL точки входу — браузер сам довантажує інші файли по мірі
-- потреби (як звичайний сайт), без JSZip і без клієнтської розпаковки.
--
-- SCORM-контент (навчальні матеріали) не є персональними/чутливими даними —
-- як і avatars/news-images/course-thumbnails, робимо бакет публічним для
-- читання (шлях містить непередбачуваний timestamp, тому пряме вгадування
-- URL стороннім максимально ускладнене).

BEGIN;

CREATE POLICY "scorm_packages_public_read" ON storage.objects
    AS PERMISSIVE FOR SELECT TO public
    USING (bucket_id = 'scorm-packages');

COMMIT;
